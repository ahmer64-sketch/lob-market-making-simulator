"""Phase 1: matching-engine benchmark and report.

Run: .venv/bin/python scripts/run_phase1.py
Writes reports/phase1_engine.md. Correctness evidence comes from the test suite (pytest);
this script measures speed on two order-flow regimes and records the test summary.
"""
import platform
import random
import subprocess
import time
from pathlib import Path

from lob.book import BUY, SELL, OrderBook

ROOT = Path(__file__).resolve().parents[1]
N = 300_000


def make_ops(seed, deep):
    rng = random.Random(seed)
    ops, next_id = [], 1
    for _ in range(N):
        u = rng.random()
        if u < (0.75 if deep else 0.55):
            side = rng.choice([BUY, SELL])
            price = 10_000 - side * rng.randint(-2, 200 if deep else 15)
            ops.append((0, side, price, rng.randint(1, 50)))
            next_id += 1
        elif u < (0.80 if deep else 0.70):
            ops.append((1, rng.choice([BUY, SELL]), rng.randint(1, 400 if deep else 80), 0))
            next_id += 1
        else:
            # cancel one of the 200 most recent orders (real cancels mostly hit recent quotes);
            # some will already have traded, which the report counts
            ops.append((2, rng.randint(max(1, next_id - 200), max(1, next_id - 1)), 0, 0))
    return ops


def run(ops):
    book = OrderBook()
    limit, market, cancel = book.limit, book.market, book.cancel
    t0 = time.perf_counter()
    trades = cancelled = max_resting = 0
    for i, (kind, a, b, c) in enumerate(ops):
        if kind == 0:
            trades += len(limit(a, b, c).trades)
        elif kind == 1:
            trades += len(market(a, b).trades)
        else:
            cancelled += cancel(a) > 0
        if i % 1000 == 0:
            max_resting = max(max_resting, len(book.orders))
    dt = time.perf_counter() - t0
    n_cancel = sum(1 for o in ops if o[0] == 2)
    levels = len(book.levels[BUY]) + len(book.levels[SELL])
    return dt, trades, len(book.orders), cancelled / n_cancel, levels


if __name__ == "__main__":
    lines = ["# Phase 1: matching engine\n"]
    tests = subprocess.run([str(ROOT / ".venv/bin/pytest"), "-q"], cwd=ROOT, capture_output=True, text=True)
    summary = tests.stdout.strip().splitlines()[-1]
    lines += ["## Correctness\n",
              f"Test suite: **{summary}** (`pytest`):\n",
              "- **Unit tests** for every rule: price priority, FIFO within a price, partial fills keeping their place in "
              "the queue, market orders sweeping levels, cancels (O(1), idempotent, after a fill), post-only rejection, "
              "immediate-or-cancel, integer-tick prices, imbalance and microprice.",
              "- **Against a reference engine:** a deliberately naive book (one flat list, re-sorted on every match) "
              "must produce identical trades and identical books on (a) 400 order sequences generated by `hypothesis`, "
              "(b) 100,000 random events with a shallow, fast-trading book, and (c) 30,000 events building a deep book "
              "of over 1,000 resting orders across more than 200 price levels.",
              "- **Invariants after every event:** best bid < best ask (never crossed); every level's total equals the "
              "sum of its orders; orders inside a level are in arrival order; and quantity is conserved: everything "
              "submitted is filled, resting, cancelled or discarded.",
              "- **The tests were themselves tested** by planting two bugs (serving the newest order first; printing "
              "trades at the taker's price instead of the resting order's): both were caught immediately.\n"]

    lines += ["## Speed\n",
              f"{N:,} events per regime, pure Python {platform.python_version()} on {platform.machine()}, best of 3 runs:\n",
              "| Regime | Events / second | Trades | Cancels that removed an order | Resting orders at end | Price levels at end |",
              "|---|---|---|---|---|---|"]
    for name, deep in (("narrow price range, 15% market orders", False), ("wide price range, 5% market orders", True)):
        ops = make_ops(1, deep)
        best = min((run(ops) for _ in range(3)), key=lambda r: r[0])
        lines.append(f"| {name} | **{N / best[0]:,.0f}** | {best[1]:,} | {best[3]:.0%} | {best[2]:,} | {best[4]} |")
    lines += ["\nThis flow is a stress test, not a realistic market: more quantity arrives as limit orders than market "
              "orders and cancels remove, so the book grows to tens of thousands of orders, and only 37–56% of cancels "
              "hit an order still resting (the rest target orders that already traded). Realistic, balanced order "
              "flow is built in Phase 2.\n",
              "Design: integer ticks; per price level an insertion-ordered dict (FIFO, O(1) cancel); a heap per side "
              "for the best price with lazy removal of emptied levels; an order-id map for O(1) lookup. Faster options "
              "for later (Numba, array-based levels, C++/Rust) are discussed in the final README."]
    (ROOT / "reports/phase1_engine.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
